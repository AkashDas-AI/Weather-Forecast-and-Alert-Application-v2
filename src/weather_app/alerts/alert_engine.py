"""Rule-based weather advisory alert engine.

Author: Akash Das

Note: Alerts generated by this module are educational, threshold-based
advisories and must not be treated as official meteorological warnings.
"""

from dataclasses import dataclass
from datetime import date, datetime
from enum import Enum

from weather_app.alerts.thresholds import AlertThresholds
from weather_app.analysis.forecast_analysis import (
    ForecastAnalysis,
    describe_weather_code,
)

EDUCATIONAL_DISCLAIMER = (
    "Educational advisory only: generated from configurable application thresholds "
    "and not an official meteorological warning."
)

THUNDERSTORM_CODES: frozenset[int] = frozenset({95, 96, 99})


class AlertCategory(str, Enum):
    """Supported weather advisory categories."""

    HIGH_TEMPERATURE = "high_temperature"
    LOW_TEMPERATURE = "low_temperature"
    PRECIPITATION = "precipitation"
    HIGH_HUMIDITY = "high_humidity"
    STRONG_WIND = "strong_wind"
    WEATHER_CONDITION = "weather_condition"


class AlertSeverity(str, Enum):
    """Advisory severity levels."""

    INFO = "info"
    ADVISORY = "advisory"
    WARNING = "warning"


class AlertScope(str, Enum):
    """Forecast time scope of an alert."""

    CURRENT = "current"
    HOURLY = "hourly"
    DAILY = "daily"


@dataclass(frozen=True)
class WeatherAlert:
    """Immutable weather advisory alert record."""

    alert_id: str
    category: AlertCategory
    severity: AlertSeverity
    title: str
    description: str
    timestamp: datetime | date
    measured_value: float | int
    unit: str
    threshold_context: str
    scope: AlertScope


@dataclass(frozen=True)
class AlertEvaluation:
    """Result of evaluating a ForecastAnalysis against AlertThresholds."""

    alerts: tuple[WeatherAlert, ...]
    thresholds: AlertThresholds
    total_count: int
    disclaimer: str = EDUCATIONAL_DISCLAIMER


def _add_alert(
    alerts: list[WeatherAlert],
    seen_ids: set[str],
    *,
    rule_key: str,
    category: AlertCategory,
    severity: AlertSeverity,
    title: str,
    description: str,
    timestamp: datetime | date,
    measured_value: float | int,
    unit: str,
    threshold_context: str,
    scope: AlertScope,
) -> None:
    """Append a WeatherAlert if its deterministic alert_id has not been seen."""
    alert_id = f"{scope.value}:{rule_key}:{timestamp.isoformat()}"
    if alert_id in seen_ids:
        return
    seen_ids.add(alert_id)
    alerts.append(
        WeatherAlert(
            alert_id=alert_id,
            category=category,
            severity=severity,
            title=title,
            description=description,
            timestamp=timestamp,
            measured_value=measured_value,
            unit=unit,
            threshold_context=threshold_context,
            scope=scope,
        )
    )


def _evaluate_temperature_pair(
    alerts: list[WeatherAlert],
    seen_ids: set[str],
    *,
    high_val: float | None,
    low_val: float | None,
    timestamp: datetime | date,
    scope: AlertScope,
    thresholds: AlertThresholds,
) -> None:
    if high_val is not None and high_val >= thresholds.high_temp_c:
        _add_alert(
            alerts,
            seen_ids,
            rule_key="high_temperature",
            category=AlertCategory.HIGH_TEMPERATURE,
            severity=AlertSeverity.ADVISORY,
            title="High Temperature Advisory",
            description=f"Temperature of {high_val:.1f} °C meets or exceeds {thresholds.high_temp_c:.1f} °C.",
            timestamp=timestamp,
            measured_value=high_val,
            unit="°C",
            threshold_context=f">= {thresholds.high_temp_c:.1f} °C",
            scope=scope,
        )
    if low_val is not None and low_val <= thresholds.low_temp_c:
        _add_alert(
            alerts,
            seen_ids,
            rule_key="low_temperature",
            category=AlertCategory.LOW_TEMPERATURE,
            severity=AlertSeverity.ADVISORY,
            title="Low Temperature Advisory",
            description=f"Temperature of {low_val:.1f} °C is at or below {thresholds.low_temp_c:.1f} °C.",
            timestamp=timestamp,
            measured_value=low_val,
            unit="°C",
            threshold_context=f"<= {thresholds.low_temp_c:.1f} °C",
            scope=scope,
        )


def _evaluate_weather_code(
    alerts: list[WeatherAlert],
    seen_ids: set[str],
    *,
    code: int | None,
    timestamp: datetime | date,
    scope: AlertScope,
    thresholds: AlertThresholds,
) -> None:
    if code is None or code not in thresholds.severe_weather_codes:
        return
    description_text = describe_weather_code(code)
    severity = AlertSeverity.WARNING if code in THUNDERSTORM_CODES else AlertSeverity.ADVISORY
    _add_alert(
        alerts,
        seen_ids,
        rule_key="weather_condition",
        category=AlertCategory.WEATHER_CONDITION,
        severity=severity,
        title=f"Weather Condition Advisory: {description_text}",
        description=f"Reported weather code {code} ({description_text}) is in configured advisory codes.",
        timestamp=timestamp,
        measured_value=code,
        unit="WMO code",
        threshold_context=f"code in {thresholds.severe_weather_codes}",
        scope=scope,
    )


def _evaluate_wind(
    alerts: list[WeatherAlert],
    seen_ids: set[str],
    *,
    speed_kmh: float | None,
    timestamp: datetime | date,
    scope: AlertScope,
    thresholds: AlertThresholds,
) -> None:
    if speed_kmh is not None and speed_kmh >= thresholds.strong_wind_kmh:
        _add_alert(
            alerts,
            seen_ids,
            rule_key="strong_wind",
            category=AlertCategory.STRONG_WIND,
            severity=AlertSeverity.ADVISORY,
            title="Strong Wind Advisory",
            description=f"Wind speed of {speed_kmh:.1f} km/h meets or exceeds {thresholds.strong_wind_kmh:.1f} km/h.",
            timestamp=timestamp,
            measured_value=speed_kmh,
            unit="km/h",
            threshold_context=f">= {thresholds.strong_wind_kmh:.1f} km/h",
            scope=scope,
        )


def evaluate_alerts(
    analysis: ForecastAnalysis,
    thresholds: AlertThresholds | None = None,
) -> AlertEvaluation:
    """Evaluate a ForecastAnalysis against configurable AlertThresholds."""
    if not isinstance(analysis, ForecastAnalysis):
        raise TypeError("analysis must be a ForecastAnalysis instance.")
    if thresholds is None:
        active_thresholds = AlertThresholds()
    elif isinstance(thresholds, AlertThresholds):
        active_thresholds = thresholds
    else:
        raise TypeError("thresholds must be an AlertThresholds instance or None.")

    alerts: list[WeatherAlert] = []
    seen_ids: set[str] = set()

    # 1. Current conditions
    cur = analysis.current
    _evaluate_temperature_pair(
        alerts,
        seen_ids,
        high_val=cur.temperature_c,
        low_val=cur.temperature_c,
        timestamp=cur.time,
        scope=AlertScope.CURRENT,
        thresholds=active_thresholds,
    )
    if (
        cur.relative_humidity_pct is not None
        and cur.relative_humidity_pct >= active_thresholds.high_humidity_pct
    ):
        _add_alert(
            alerts,
            seen_ids,
            rule_key="high_humidity",
            category=AlertCategory.HIGH_HUMIDITY,
            severity=AlertSeverity.INFO,
            title="High Humidity Advisory",
            description=(
                f"Relative humidity of {cur.relative_humidity_pct:.1f}% meets or exceeds "
                f"{active_thresholds.high_humidity_pct:.1f}%."
            ),
            timestamp=cur.time,
            measured_value=cur.relative_humidity_pct,
            unit="%",
            threshold_context=f">= {active_thresholds.high_humidity_pct:.1f} %",
            scope=AlertScope.CURRENT,
        )
    if (
        cur.precipitation_mm is not None
        and cur.precipitation_mm >= active_thresholds.heavy_rain_hourly_mm
    ):
        _add_alert(
            alerts,
            seen_ids,
            rule_key="heavy_rain",
            category=AlertCategory.PRECIPITATION,
            severity=AlertSeverity.ADVISORY,
            title="Heavy Precipitation Advisory",
            description=(
                f"Current precipitation of {cur.precipitation_mm:.1f} mm meets or exceeds "
                f"{active_thresholds.heavy_rain_hourly_mm:.1f} mm."
            ),
            timestamp=cur.time,
            measured_value=cur.precipitation_mm,
            unit="mm",
            threshold_context=f">= {active_thresholds.heavy_rain_hourly_mm:.1f} mm",
            scope=AlertScope.CURRENT,
        )
    _evaluate_wind(
        alerts,
        seen_ids,
        speed_kmh=cur.wind_speed_kmh,
        timestamp=cur.time,
        scope=AlertScope.CURRENT,
        thresholds=active_thresholds,
    )
    _evaluate_weather_code(
        alerts,
        seen_ids,
        code=cur.weather_code,
        timestamp=cur.time,
        scope=AlertScope.CURRENT,
        thresholds=active_thresholds,
    )

    # 2. Hourly summaries
    for h in analysis.hourly_summaries:
        _evaluate_temperature_pair(
            alerts,
            seen_ids,
            high_val=h.temperature_c,
            low_val=h.temperature_c,
            timestamp=h.time,
            scope=AlertScope.HOURLY,
            thresholds=active_thresholds,
        )
        if (
            h.precipitation_mm is not None
            and h.precipitation_mm >= active_thresholds.heavy_rain_hourly_mm
        ):
            _add_alert(
                alerts,
                seen_ids,
                rule_key="heavy_rain",
                category=AlertCategory.PRECIPITATION,
                severity=AlertSeverity.ADVISORY,
                title="Hourly Heavy Precipitation Advisory",
                description=(
                    f"Hourly precipitation of {h.precipitation_mm:.1f} mm meets or exceeds "
                    f"{active_thresholds.heavy_rain_hourly_mm:.1f} mm."
                ),
                timestamp=h.time,
                measured_value=h.precipitation_mm,
                unit="mm",
                threshold_context=f">= {active_thresholds.heavy_rain_hourly_mm:.1f} mm",
                scope=AlertScope.HOURLY,
            )
        if (
            h.precipitation_probability_pct is not None
            and h.precipitation_probability_pct >= active_thresholds.high_precip_probability_pct
        ):
            _add_alert(
                alerts,
                seen_ids,
                rule_key="precip_probability",
                category=AlertCategory.PRECIPITATION,
                severity=AlertSeverity.INFO,
                title="High Precipitation Probability Advisory",
                description=(
                    f"Hourly precipitation probability of {h.precipitation_probability_pct:.1f}% "
                    f"meets or exceeds {active_thresholds.high_precip_probability_pct:.1f}%."
                ),
                timestamp=h.time,
                measured_value=h.precipitation_probability_pct,
                unit="%",
                threshold_context=f">= {active_thresholds.high_precip_probability_pct:.1f} %",
                scope=AlertScope.HOURLY,
            )
        _evaluate_wind(
            alerts,
            seen_ids,
            speed_kmh=h.wind_speed_kmh,
            timestamp=h.time,
            scope=AlertScope.HOURLY,
            thresholds=active_thresholds,
        )
        _evaluate_weather_code(
            alerts,
            seen_ids,
            code=h.weather_code,
            timestamp=h.time,
            scope=AlertScope.HOURLY,
            thresholds=active_thresholds,
        )

    # 3. Daily summaries
    for d in analysis.daily_summaries:
        _evaluate_temperature_pair(
            alerts,
            seen_ids,
            high_val=d.temp_max_c,
            low_val=d.temp_min_c,
            timestamp=d.date,
            scope=AlertScope.DAILY,
            thresholds=active_thresholds,
        )
        if (
            d.precipitation_sum_mm is not None
            and d.precipitation_sum_mm >= active_thresholds.heavy_rain_daily_mm
        ):
            _add_alert(
                alerts,
                seen_ids,
                rule_key="heavy_rain",
                category=AlertCategory.PRECIPITATION,
                severity=AlertSeverity.ADVISORY,
                title="Daily Heavy Precipitation Advisory",
                description=(
                    f"Daily precipitation total of {d.precipitation_sum_mm:.1f} mm meets or "
                    f"exceeds {active_thresholds.heavy_rain_daily_mm:.1f} mm."
                ),
                timestamp=d.date,
                measured_value=d.precipitation_sum_mm,
                unit="mm",
                threshold_context=f">= {active_thresholds.heavy_rain_daily_mm:.1f} mm",
                scope=AlertScope.DAILY,
            )
        if (
            d.precipitation_probability_max_pct is not None
            and d.precipitation_probability_max_pct >= active_thresholds.high_precip_probability_pct
        ):
            _add_alert(
                alerts,
                seen_ids,
                rule_key="precip_probability",
                category=AlertCategory.PRECIPITATION,
                severity=AlertSeverity.INFO,
                title="Daily Precipitation Probability Advisory",
                description=(
                    f"Daily max precipitation probability of {d.precipitation_probability_max_pct:.1f}% "
                    f"meets or exceeds {active_thresholds.high_precip_probability_pct:.1f}%."
                ),
                timestamp=d.date,
                measured_value=d.precipitation_probability_max_pct,
                unit="%",
                threshold_context=f">= {active_thresholds.high_precip_probability_pct:.1f} %",
                scope=AlertScope.DAILY,
            )
        _evaluate_wind(
            alerts,
            seen_ids,
            speed_kmh=d.wind_speed_max_kmh,
            timestamp=d.date,
            scope=AlertScope.DAILY,
            thresholds=active_thresholds,
        )
        _evaluate_weather_code(
            alerts,
            seen_ids,
            code=d.weather_code,
            timestamp=d.date,
            scope=AlertScope.DAILY,
            thresholds=active_thresholds,
        )

    return AlertEvaluation(
        alerts=tuple(alerts),
        thresholds=active_thresholds,
        total_count=len(alerts),
    )
