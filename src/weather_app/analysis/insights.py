"""Deterministic, rule-based weather insights and interpretation layer.

Author: Akash Das

Note: Interpretations generated by this module are educational summaries of
measured/forecast data and must not be treated as official meteorological,
safety-critical, or medical advice.
"""

from __future__ import annotations

from dataclasses import dataclass
from typing import TYPE_CHECKING

from weather_app.analysis.forecast_analysis import ForecastAnalysis

if TYPE_CHECKING:
    from weather_app.alerts.alert_engine import AlertEvaluation

INSIGHTS_DISCLAIMER = (
    "Application-generated educational interpretation based on forecast data; "
    "not official meteorological, safety-critical, or medical advice."
)


@dataclass(frozen=True)
class WeatherInsights:
    """Structured beginner-friendly interpretation of a ForecastAnalysis."""

    overview: str
    temperature_insights: tuple[str, ...]
    precipitation_insights: tuple[str, ...]
    humidity_insights: tuple[str, ...]
    wind_insights: tuple[str, ...]
    condition_insights: tuple[str, ...]
    advisory_insights: tuple[str, ...]
    disclaimer: str = INSIGHTS_DISCLAIMER


def generate_temperature_insights(analysis: ForecastAnalysis) -> tuple[str, ...]:
    """Generate plain-language temperature pattern and range insights."""
    if not isinstance(analysis, ForecastAnalysis):
        raise TypeError("analysis must be a ForecastAnalysis instance.")

    insights: list[str] = []
    temp = analysis.temperature

    if analysis.hourly_summaries:
        warmest = max(analysis.hourly_summaries, key=lambda h: h.temperature_c)
        coolest = min(analysis.hourly_summaries, key=lambda h: h.temperature_c)
        insights.append(
            f"Hourly temperatures span from {coolest.temperature_c:.1f} °C "
            f"(around {coolest.time.strftime('%Y-%m-%d %H:%M')} local) to "
            f"{warmest.temperature_c:.1f} °C (around {warmest.time.strftime('%Y-%m-%d %H:%M')} local)."
        )

        if len(analysis.hourly_summaries) >= 2:
            mid = len(analysis.hourly_summaries) // 2
            first_half = analysis.hourly_summaries[:mid]
            second_half = analysis.hourly_summaries[mid:]
            first_avg = sum(h.temperature_c for h in first_half) / len(first_half)
            second_avg = sum(h.temperature_c for h in second_half) / len(second_half)
            delta = second_avg - first_avg
            if delta >= 2.0:
                insights.append(
                    f"A warming pattern appears across the hourly window, rising by "
                    f"{delta:.1f} °C on average between the first and second halves."
                )
            elif delta <= -2.0:
                insights.append(
                    f"A cooling pattern appears across the hourly window, dropping by "
                    f"{abs(delta):.1f} °C on average between the first and second halves."
                )
            else:
                insights.append(
                    "Hourly temperatures remain relatively steady across the forecast window."
                )
    else:
        insights.append(
            f"Only the current temperature ({temp.current_c:.1f} °C) is available; "
            "hourly temperature series are not present."
        )

    if analysis.daily_summaries:
        ranges = [(d.date, d.temp_max_c - d.temp_min_c) for d in analysis.daily_summaries]
        widest_date, widest_span = max(ranges, key=lambda item: item[1])
        avg_span = sum(span for _, span in ranges) / len(ranges)
        insights.append(
            f"Daily temperature swings average {avg_span:.1f} °C, with the widest "
            f"variation of {widest_span:.1f} °C on {widest_date.isoformat()}."
        )

    return tuple(insights)


def generate_precipitation_insights(analysis: ForecastAnalysis) -> tuple[str, ...]:
    """Generate precipitation amount and probability insights without conflating them."""
    if not isinstance(analysis, ForecastAnalysis):
        raise TypeError("analysis must be a ForecastAnalysis instance.")

    insights: list[str] = []
    precip = analysis.precipitation

    if precip.hourly_amount_count > 0 and precip.hourly_total_mm is not None:
        if precip.hourly_total_mm == 0.0:
            insights.append("No measurable hourly rainfall accumulation (0.0 mm) is forecast.")
        else:
            insights.append(
                f"Forecast hourly precipitation totals {precip.hourly_total_mm:.1f} mm "
                f"(peak {precip.hourly_max_mm:.1f} mm in a single hour)."
            )
    elif precip.daily_amount_count > 0 and precip.daily_total_mm is not None:
        insights.append(
            f"Daily forecast precipitation totals {precip.daily_total_mm:.1f} mm."
        )
    else:
        insights.append("Hourly and daily precipitation amount data are unavailable.")

    hourly_with_prob = [
        h for h in analysis.hourly_summaries if h.precipitation_probability_pct is not None
    ]
    if hourly_with_prob:
        peak_prob = max(
            hourly_with_prob,
            key=lambda h: h.precipitation_probability_pct or 0.0,
        )
        insights.append(
            f"Peak precipitation probability reaches "
            f"{peak_prob.precipitation_probability_pct:.0f}% around "
            f"{peak_prob.time.strftime('%Y-%m-%d %H:%M')} local "
            "(probability indicates forecast likelihood, not guaranteed rainfall)."
        )
    elif precip.daily_max_probability_pct is not None:
        insights.append(
            f"Daily maximum precipitation probability reaches "
            f"{precip.daily_max_probability_pct:.0f}% "
            "(probability reflects likelihood rather than guaranteed accumulation)."
        )

    return tuple(insights)


def generate_humidity_insights(analysis: ForecastAnalysis) -> tuple[str, ...]:
    """Generate relative humidity insights, skipping unavailable observations."""
    if not isinstance(analysis, ForecastAnalysis):
        raise TypeError("analysis must be a ForecastAnalysis instance.")

    hum = analysis.humidity
    if not hum.has_sufficient_data and hum.current_pct is None:
        return ("Relative humidity measurements are unavailable for this forecast.",)

    insights: list[str] = []
    if hum.has_sufficient_data and hum.hourly_avg_pct is not None:
        if hum.hourly_avg_pct >= 75.0:
            feel = "relatively humid"
        elif hum.hourly_avg_pct <= 35.0:
            feel = "relatively dry"
        else:
            feel = "moderate"
        insights.append(
            f"Hourly relative humidity is {feel} on average ({hum.hourly_avg_pct:.0f}%), "
            f"ranging from {hum.hourly_min_pct:.0f}% to {hum.hourly_max_pct:.0f}%."
        )
    elif hum.current_pct is not None:
        insights.append(
            f"Current relative humidity is {hum.current_pct:.0f}%; hourly humidity data is unavailable."
        )
    return tuple(insights)


def generate_wind_insights(analysis: ForecastAnalysis) -> tuple[str, ...]:
    """Generate descriptive wind-speed insights without inferring storm severity."""
    if not isinstance(analysis, ForecastAnalysis):
        raise TypeError("analysis must be a ForecastAnalysis instance.")

    wind = analysis.wind
    if (
        wind.current_speed_kmh is None
        and wind.hourly_sample_count == 0
        and wind.daily_sample_count == 0
    ):
        return ("Wind speed measurements are unavailable for this forecast.",)

    insights: list[str] = []
    if wind.hourly_sample_count > 0 and wind.hourly_avg_speed_kmh is not None:
        insights.append(
            f"Hourly wind speeds average {wind.hourly_avg_speed_kmh:.1f} km/h "
            f"and peak at {wind.hourly_max_speed_kmh:.1f} km/h."
        )
    if wind.daily_sample_count > 0 and wind.daily_max_speed_kmh is not None:
        insights.append(
            f"Daily maximum forecast wind speed reaches {wind.daily_max_speed_kmh:.1f} km/h."
        )
    if not insights and wind.current_speed_kmh is not None:
        insights.append(
            f"Current wind speed is {wind.current_speed_kmh:.1f} km/h; "
            "extended wind series are unavailable."
        )
    return tuple(insights)


def generate_condition_insights(analysis: ForecastAnalysis) -> tuple[str, ...]:
    """Summarize forecast weather-code descriptions and transitions."""
    if not isinstance(analysis, ForecastAnalysis):
        raise TypeError("analysis must be a ForecastAnalysis instance.")

    if not analysis.hourly_summaries and not analysis.daily_summaries:
        return (
            f"Current reported condition is '{analysis.current.condition_description}'; "
            "no extended hourly or daily condition series are available.",
        )

    insights: list[str] = []
    if analysis.hourly_summaries:
        descriptions = [h.condition_description for h in analysis.hourly_summaries]
        unique_desc = list(dict.fromkeys(descriptions))
        if len(unique_desc) == 1:
            insights.append(
                f"Forecast hourly sky/weather conditions remain consistent as '{unique_desc[0]}'."
            )
        else:
            transitions: list[str] = []
            for prev, curr in zip(analysis.hourly_summaries, analysis.hourly_summaries[1:]):
                if prev.condition_description != curr.condition_description:
                    transitions.append(
                        f"{prev.condition_description} -> {curr.condition_description} "
                        f"at {curr.time.strftime('%Y-%m-%d %H:%M')}"
                    )
            preview = "; ".join(transitions[:3])
            suffix = f" (and {len(transitions) - 3} more)" if len(transitions) > 3 else ""
            insights.append(
                f"Hourly conditions transition across {len(unique_desc)} states: {preview}{suffix}."
            )

    if analysis.daily_summaries:
        daily_desc = list(dict.fromkeys(d.condition_description for d in analysis.daily_summaries))
        insights.append(
            f"Daily summaries cover {len(analysis.daily_summaries)} day(s) with "
            f"conditions: {', '.join(daily_desc)}."
        )

    return tuple(insights)


def generate_advisory_insights(evaluation: AlertEvaluation | None) -> tuple[str, ...]:
    """Explain Phase 7 educational advisories in accessible language."""
    if evaluation is None:
        return ("No alert evaluation was provided for advisory interpretation.",)

    from weather_app.alerts.alert_engine import AlertEvaluation, AlertSeverity

    if not isinstance(evaluation, AlertEvaluation):
        raise TypeError("evaluation must be an AlertEvaluation instance or None.")

    if evaluation.total_count == 0:
        return (
            "No educational advisories were triggered, indicating forecast values "
            "stay within the configured thresholds.",
        )

    warnings = sum(1 for a in evaluation.alerts if a.severity == AlertSeverity.WARNING)
    advisories = sum(1 for a in evaluation.alerts if a.severity == AlertSeverity.ADVISORY)
    infos = sum(1 for a in evaluation.alerts if a.severity == AlertSeverity.INFO)
    categories = ", ".join(sorted({a.category.value for a in evaluation.alerts}))

    return (
        f"{evaluation.total_count} educational advisory item(s) triggered "
        f"({warnings} warning, {advisories} advisory, {infos} info) across "
        f"categories: {categories}.",
        "These items highlight forecast values meeting configured application thresholds "
        "and are not official meteorological warnings.",
    )


def generate_weather_insights(
    analysis: ForecastAnalysis,
    evaluation: AlertEvaluation | None = None,
) -> WeatherInsights:
    """Generate a complete WeatherInsights bundle from analysis and alert evaluation."""
    if not isinstance(analysis, ForecastAnalysis):
        raise TypeError("analysis must be a ForecastAnalysis instance.")

    temp_insights = generate_temperature_insights(analysis)
    precip_insights = generate_precipitation_insights(analysis)
    hum_insights = generate_humidity_insights(analysis)
    wind_insights = generate_wind_insights(analysis)
    cond_insights = generate_condition_insights(analysis)
    adv_insights = generate_advisory_insights(evaluation)

    alert_note = (
        f"{evaluation.total_count} educational advisory item(s) active."
        if evaluation is not None and evaluation.total_count > 0
        else "No educational advisories triggered."
    )
    overview = (
        f"Forecast for ({analysis.latitude:.2f}, {analysis.longitude:.2f}) in timezone "
        f"'{analysis.timezone}' currently reports '{analysis.current.condition_description}' "
        f"at {analysis.current.temperature_c:.1f} °C. {alert_note}"
    )

    return WeatherInsights(
        overview=overview,
        temperature_insights=temp_insights,
        precipitation_insights=precip_insights,
        humidity_insights=hum_insights,
        wind_insights=wind_insights,
        condition_insights=cond_insights,
        advisory_insights=adv_insights,
    )
